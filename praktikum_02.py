# Inisialisasi list angka
angka = [10, 20, 30, 40, 50, 60]

# 1. Menampilkan angka indeks 1 sampai sebelum indeks 4
print(angka[1:4])

# 2. Menampilkan elemen mulai indeks 3 sampai akhir
print(angka[3:])

# 3. Menampilkan tiga elemen pertama
print(angka[:3])

# 4. Menampilkan list terbalik (slicing dengan step -1)
print(angka[::-1])  # slicing untuk membalik